// Context7 download fallback.
//
// Context7 is wired as a hosted MCP server by default. Some clients cannot use
// remote MCP servers, and sometimes an agent needs a durable copy of the docs
// it used. This module fetches a focused slice of a library's documentation
// through Context7's public REST API and saves it under `.sdrive/context/`.
const fs = require("fs");
const path = require("path");

const CONTEXT7_API = "https://context7.com/api/v2";
const DEFAULT_QUERY = "overview";
const DEFAULT_TOKENS = 8000;
const GENERATED_MARKER = "<!-- generated by sdrive knowledge:fetch (context7) -->";

function oneLine(value) {
  return String(value === undefined || value === null ? "" : value)
    .replace(/[\r\n]+/g, " ")
    .replace(/`/g, "'")
    .trim();
}

function slug(value) {
  return (
    oneLine(value)
      .replace(/^\/+/, "")
      .replace(/[^a-zA-Z0-9._-]+/g, "-")
      .replace(/-+/g, "-")
      .replace(/^[-.]+|[-.]+$/g, "")
      .toLowerCase()
      .slice(0, 80) || "library"
  );
}

function authorizationHeaders(apiKey) {
  return apiKey ? { Authorization: `Bearer ${apiKey}` } : {};
}

function truncate(value, length = 240) {
  const text = String(value || "").replace(/\s+/g, " ").trim();
  return text.length > length ? `${text.slice(0, length)}...` : text;
}

async function fetchWithTimeout(fetchImpl, url, options, timeoutMs) {
  if (typeof fetchImpl !== "function") {
    throw new Error("This Node.js version has no fetch. Use Node 18 or later.");
  }

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);

  try {
    return await fetchImpl(url, { ...options, signal: controller.signal });
  } finally {
    clearTimeout(timer);
  }
}

async function requestText(fetchImpl, url, options, timeoutMs) {
  const response = await fetchWithTimeout(fetchImpl, url, options, timeoutMs);
  const text = await response.text();

  if (!response.ok) {
    throw new Error(`Context7 API returned ${response.status}: ${truncate(text)}`);
  }

  return text;
}

async function resolveLibrary(library, options = {}) {
  const {
    query = DEFAULT_QUERY,
    apiKey = process.env.CONTEXT7_API_KEY,
    fetchImpl = globalThis.fetch,
    timeoutMs = 30000
  } = options;

  const name = String(library || "").trim();

  if (!name) {
    throw new Error("A library name or Context7 library id is required.");
  }

  // A Context7 id is already unambiguous (`/org/project`), so skip the search
  // round-trip when the caller supplied one.
  if (name.startsWith("/")) {
    return { id: name, title: name, description: "" };
  }

  const url = new URL(`${CONTEXT7_API}/libs/search`);
  url.searchParams.set("libraryName", name);
  if (query) url.searchParams.set("query", query);

  const text = await requestText(
    fetchImpl,
    url.toString(),
    { headers: { accept: "application/json", ...authorizationHeaders(apiKey) } },
    timeoutMs
  );

  let data;

  try {
    data = JSON.parse(text);
  } catch (error) {
    throw new Error(`Context7 search returned invalid JSON: ${truncate(text)}`);
  }

  const results = Array.isArray(data.results) ? data.results : [];

  if (results.length === 0) {
    throw new Error(
      `Context7 found no library matching "${name}". Try a package name such as "next.js" or pass --library-id /org/project.`
    );
  }

  return results[0];
}

async function fetchContext(options = {}) {
  const {
    libraryId,
    query = DEFAULT_QUERY,
    tokens = DEFAULT_TOKENS,
    apiKey = process.env.CONTEXT7_API_KEY,
    fetchImpl = globalThis.fetch,
    timeoutMs = 30000
  } = options;

  if (!libraryId) {
    throw new Error("A Context7 library id is required.");
  }

  const url = new URL(`${CONTEXT7_API}/context`);
  url.searchParams.set("libraryId", libraryId);
  url.searchParams.set("query", query || DEFAULT_QUERY);
  url.searchParams.set("tokens", String(tokens));

  const text = await requestText(
    fetchImpl,
    url.toString(),
    { headers: { accept: "text/plain", ...authorizationHeaders(apiKey) } },
    timeoutMs
  );

  if (!text.trim()) {
    throw new Error(`Context7 returned no documentation for ${libraryId}.`);
  }

  return text;
}

function defaultContextPath(projectRoot, libraryId, query) {
  const name = `${slug(libraryId)}-${slug(query || DEFAULT_QUERY)}.md`;
  return path.join(projectRoot, ".sdrive", "context", "external", name);
}

function contextDocument({ library, query, tokens, text, fetchedAt }) {
  const title = oneLine(library.title || library.id);
  const id = oneLine(library.id);

  return [
    GENERATED_MARKER,
    "",
    `# ${title}`,
    "",
    `- **Library:** \`${id}\``,
    `- **Query:** ${oneLine(query || DEFAULT_QUERY)}`,
    `- **Fetched:** ${fetchedAt}`,
    `- **Token budget:** ${tokens}`,
    "",
    "> Downloaded from Context7. Re-run `sdrive knowledge:fetch` to refresh.",
    "",
    String(text || "").trim(),
    ""
  ].join("\n");
}

function writeContextFile(filePath, content, options = {}) {
  const force = options.force === true;
  const exists = fs.existsSync(filePath);

  if (exists && !force) {
    const current = fs.readFileSync(filePath, "utf8");
    if (!current.startsWith(GENERATED_MARKER)) {
      throw new Error(
        `Refusing to overwrite ${filePath}: the file was not generated by SpecDrive. Re-run with --force to replace it.`
      );
    }
  }

  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");

  return { path: filePath, overwritten: exists };
}

async function fetchAndWriteContext(options = {}) {
  const {
    projectRoot = process.cwd(),
    library,
    libraryId,
    query = DEFAULT_QUERY,
    tokens = DEFAULT_TOKENS,
    out,
    force = false,
    apiKey = process.env.CONTEXT7_API_KEY,
    fetchImpl = globalThis.fetch,
    timeoutMs = 30000
  } = options;

  if (!library && !libraryId) {
    throw new Error("A library name or Context7 library id is required.");
  }

  const normalizedTokens = Number(tokens);

  if (!Number.isInteger(normalizedTokens) || normalizedTokens <= 0) {
    throw new Error("--tokens must be a positive integer.");
  }

  const normalizedQuery = String(query || DEFAULT_QUERY).trim() || DEFAULT_QUERY;
  const resolved = libraryId
    ? { id: String(libraryId), title: String(libraryId), description: "" }
    : await resolveLibrary(library, {
        query: normalizedQuery,
        apiKey,
        fetchImpl,
        timeoutMs
      });

  const text = await fetchContext({
    libraryId: resolved.id,
    query: normalizedQuery,
    tokens: normalizedTokens,
    apiKey,
    fetchImpl,
    timeoutMs
  });

  const target = out
    ? path.resolve(projectRoot, out)
    : defaultContextPath(projectRoot, resolved.id, normalizedQuery);
  const fetchedAt = new Date().toISOString();
  const content = contextDocument({
    library: resolved,
    query: normalizedQuery,
    tokens: normalizedTokens,
    text,
    fetchedAt
  });
  const written = writeContextFile(target, content, { force });

  return {
    library: resolved,
    query: normalizedQuery,
    tokens: normalizedTokens,
    path: written.path,
    bytes: Buffer.byteLength(content, "utf8"),
    overwritten: written.overwritten,
    fetchedAt
  };
}

module.exports = {
  CONTEXT7_API,
  DEFAULT_QUERY,
  DEFAULT_TOKENS,
  GENERATED_MARKER,
  slug,
  resolveLibrary,
  fetchContext,
  defaultContextPath,
  contextDocument,
  writeContextFile,
  fetchAndWriteContext
};
